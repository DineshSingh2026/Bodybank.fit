let idSeq = 0;
/** Stable-enough unique id for a section/row/item created at build or edit time. */
function newId(prefix) {
  idSeq += 1;
  return `${prefix || 'x'}-${Date.now().toString(36)}-${idSeq.toString(36)}`;
}

function str(v, max) {
  if (v == null) return '';
  const s = typeof v === 'string' ? v : String(v);
  const cap = max || LIMITS.short;
  return s.length > cap ? s.slice(0, cap) : s;
}

function bool(v, dflt) {
  if (v === true) return true;
  if (v === false) return false;
  return !!dflt;
}

function arr(v, max) {
  if (!Array.isArray(v)) return [];
  return max && v.length > max ? v.slice(0, max) : v;
}

function pick(v, allowed, dflt) {
  const s = String(v == null ? '' : v);
  return allowed.indexOf(s) >= 0 ? s : dflt;
}

function num(v, dflt) {
  const n = Number(v);
  return Number.isFinite(n) ? n : dflt;
}

const MONTHS_LONG = ['January', 'February', 'March', 'April', 'May', 'June', 'July',
  'August', 'September', 'October', 'November', 'December'];
const MONTHS_SHORT = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

/**
 * Parse a report date without letting a timezone drag it onto the previous day.
 * A pg DATE arrives as 'YYYY-MM-DD'; treating that as UTC midnight and then reading
 * local components shifts it back a day west of Greenwich.
 */
function toLocalDate(v) {
  if (v instanceof Date) return Number.isNaN(v.getTime()) ? null : v;
  const s = String(v == null ? '' : v);
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(s);
  if (m) return new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3]));
  const d = new Date(s);
  return Number.isNaN(d.getTime()) ? null : d;
}

function formatLongDate(v) {
  const d = toLocalDate(v) || new Date();
  return `${d.getDate()} ${MONTHS_LONG[d.getMonth()]} ${d.getFullYear()}`;
}

function formatShortDate(v) {
  const d = toLocalDate(v);
  if (!d) return String(v || '—');
  return `${String(d.getDate()).padStart(2, '0')} ${MONTHS_SHORT[d.getMonth()]} ${String(d.getFullYear()).slice(2)}`;
}

function nonEmptyArray(v) { return Array.isArray(v) && v.length > 0; }

function trendArrow(delta) {
  if (delta == null || Math.abs(delta) <= 1e-9) return 'flat';
  return delta > 0 ? 'up' : 'down';
}

function trendLabel(marker) {
  if (marker.deltaPct != null) return `${marker.delta > 0 ? '+' : ''}${marker.deltaPct}%`;
  if (marker.delta != null) return `${marker.delta > 0 ? '+' : ''}${marker.delta}`;
  return '';
}

