/** True when the document would print at least one visible section. */
function docHasVisibleContent(doc) {
  if (!doc) return false;
  if (doc.cover && doc.cover.show !== false) return true;
  return (doc.sections || []).some((s) => s && s.show !== false);
}

/** The coach-note text held in the document, so `admin_notes` can stay in sync. */
function docCoachNote(doc) {
  const s = ((doc && doc.sections) || []).filter((x) => x && x.id === 'sec-coach-note')[0];
  return s && s.show !== false ? String(s.text || '') : '';
}

/**
 * Return a copy of the document with the coach note replaced (used when a note is
 * saved from outside the editor). Pure: the caller's document is left untouched, so
 * a failure mid-update cannot leave a half-edited object behind.
 */
function setDocCoachNote(input, note) {
  if (!input || !Array.isArray(input.sections)) return input;
  const doc = { ...input, sections: input.sections.map((s) => ({ ...s })) };
  const text = String(note == null ? '' : note);
  const existing = doc.sections.filter((x) => x && x.id === 'sec-coach-note')[0];
  if (existing) {
    existing.text = text;
    existing.show = !!text;
    return doc;
  }
  const disclaimerAt = doc.sections.findIndex((x) => x && x.type === 'disclaimer');
  const section = {
    id: 'sec-coach-note',
    type: 'callout',
    show: !!text,
    pageBreak: false,
    title: '',
    subtitle: 'A Note From Your Coach',
    label: '',
    tone: 'gold',
    italic: true,
    text
  };
  if (disclaimerAt >= 0) doc.sections.splice(disclaimerAt, 0, section);
  else doc.sections.push(section);
  return doc;
}

