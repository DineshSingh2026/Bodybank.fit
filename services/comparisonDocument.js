'use strict';

/**
 * BodyBank — the EDITABLE progress-report document.
 *
 * The blood-comparison PDF used to be rendered straight off `comparison_data` +
 * `ai_verdict`. That made it un-editable: whatever Claude wrote is what the client
 * received. This module introduces a middle layer — a plain-JSON **document** that
 * describes the report as an ordered list of renderable sections.
 *
 *   raw comparison + AI verdict  ──buildComparisonDoc()──▶  doc  ──PDFKit──▶  PDF
 *                                                           ▲
 *                                             doctor edits it in the app
 *
 * The doc is the single source of truth for rendering, so "what the doctor sees in
 * the editor" and "what prints" cannot drift. When a comparison has never been
 * edited we build the default doc on the fly; once it has, the stored doc wins.
 *
 * Section types (all share id/type/show/pageBreak/title/subtitle):
 *   trend      — the marker-per-test-date table
 *   text       — heading + optional badge + prose
 *   cards      — grouped "what changed" cards (improvements / concerns / watch)
 *   table      — generic column+row table (recommendations, supplements, retests)
 *   callout    — a boxed highlight (bottom line, coach's note)
 *   disclaimer — the medical disclaimer block
 *
 * Every section can be hidden, retitled, reordered, or deleted, and new text /
 * table / cards / callout sections can be added anywhere. That is what gives the
 * reviewing doctor full control over the final printout.
 */

const DOC_VERSION = 1;

// Guard rails for anything arriving from the browser. Generous enough that no real
// report hits them, tight enough that a malformed payload can't blow up the PDF.
const LIMITS = {
  sections: 80,
  title: 240,
  body: 40000,
  short: 600,
  tableColumns: 10,
  tableRows: 400,
  cardGroups: 16,
  cardItems: 200,
  trendPanels: 60,
  trendMarkers: 300,
  trendColumns: 12,
  statItems: 8
};

const CARD_TONES = ['good', 'bad', 'watch'];
const CALLOUT_TONES = ['green', 'gold', 'amber', 'red', 'blue'];
const COLUMN_STYLES = ['normal', 'strong', 'muted', 'accent', 'warn', 'action'];
const TREND_DIRS = ['improving', 'worsening', 'stable', 'changed', 'na'];
const SECTION_TYPES = ['trend', 'text', 'cards', 'table', 'callout', 'disclaimer'];

const DEFAULT_DISCLAIMER =
  'This progress report is generated by BodyBank.fit’s AI Health System from your own previous blood analyses. ' +
  'It does not constitute a medical diagnosis. All supplement and dietary recommendations must be reviewed with your ' +
  'physician before implementation.';

const DEFAULT_COVER_FOOTNOTE =
  'This progress report compares your own previous BodyBank blood analyses. It is for informational purposes only and ' +
  'does not constitute a medical diagnosis. Please review it with your physician.';

